#!/usr/bin/env tsx
/**
 * Switch the workspace to another supported NestJS major, so CI (or a contributor) can run the
 * suites and the example app against it:
 *
 *   pnpm nestjs:use 12 && pnpm install --no-frozen-lockfile   # NestJS 12
 *   pnpm nestjs:use 11 && git checkout pnpm-lock.yaml && pnpm install   # back to the default
 *
 * The committed manifests and lockfile stay on NestJS 11: the packages ship CommonJS, and NestJS 12
 * is ESM only, so a CommonJS `require()` of it fails wherever require(esm) is unavailable, such as
 * the example app's Vercel functions. Other majors are applied as pnpm `overrides` in
 * `pnpm-workspace.yaml`, in a marked block this script adds or removes: the manifests stay
 * untouched, and every copy of a package in the graph is forced to the same major. Peer ranges
 * need no change: they already accept every supported major.
 */
import { readFileSync, writeFileSync } from 'node:fs';

type Ranges = Record<string, string>;

const DEFAULT_MAJOR = '11';

/**
 * Ranges per non-default NestJS major. Only the packages whose major follows NestJS's own belong
 * here; the others already accept both majors (`@nestjs/typeorm` 12, `@mikro-orm/nestjs` 7.1,
 * `nest-winston` 2…) or never load the framework at runtime (`@nestjs/cli`).
 */
const RANGES_BY_MAJOR: Record<string, Ranges> = {
  '12': {
    '@nestjs/common': '^12.1.3',
    '@nestjs/core': '^12.1.3',
    '@nestjs/testing': '^12.1.3',
    '@nestjs/platform-express': '^12.1.3',
    '@nestjs/platform-fastify': '^12.1.3',
    '@nestjs/graphql': '^14.0.3',
    '@nestjs/apollo': '^14.0.3',
    '@nestjs/mercurius': '^14.0.3',
    '@nestjs/config': '^12.0.1',
    '@nestjs/cache-manager': '^12.0.1',
    '@nestjs/event-emitter': '^12.0.1',
    '@nestjs/mongoose': '^12.0.0',
    '@nestjs/axios': '^12.0.1',
    '@nestjs/swagger': '^12.0.2',
  },
};

const WORKSPACE_FILE = 'pnpm-workspace.yaml';
const BLOCK_START =
  '  # nestjs:use — begin (generated by scripts/use-nestjs-version.ts, do not commit)';
const BLOCK_END = '  # nestjs:use — end';

/** Drops a block written by a previous run, so switching majors never stacks overrides. */
function withoutBlock(source: string): string {
  const start = source.indexOf(BLOCK_START);
  const end = source.indexOf(BLOCK_END);
  if (start === -1 || end === -1) return source;
  return source.slice(0, start) + source.slice(end + BLOCK_END.length + 1);
}

const major = process.argv[2] ?? '';
const ranges = RANGES_BY_MAJOR[major];
if (!ranges && major !== DEFAULT_MAJOR) {
  const majors = [DEFAULT_MAJOR, ...Object.keys(RANGES_BY_MAJOR)];
  console.error(`Usage: pnpm nestjs:use <${majors.join('|')}>`);
  process.exit(1);
}

let workspace = withoutBlock(readFileSync(WORKSPACE_FILE, 'utf8'));
if (ranges) {
  const entries = Object.entries(ranges).map(([name, range]) => `  '${name}': '${range}'`);
  const block = [BLOCK_START, ...entries, BLOCK_END].join('\n');
  workspace = /^overrides:\n/m.test(workspace)
    ? workspace.replace(/^overrides:\n/m, `overrides:\n${block}\n`)
    : `${workspace.trimEnd()}\n\noverrides:\n${block}\n`;
}
writeFileSync(WORKSPACE_FILE, workspace);

console.log(
  ranges
    ? `NestJS ${major} overrides written to ${WORKSPACE_FILE}: run \`pnpm install --no-frozen-lockfile\`.`
    : `NestJS overrides removed from ${WORKSPACE_FILE}: restore pnpm-lock.yaml, then run \`pnpm install\`.`,
);
